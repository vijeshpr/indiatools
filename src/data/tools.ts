export function searchTools(query: string): ToolDefinition[] {
  if (!query.trim()) return TOOLS

  const q = query.toLowerCase().trim()
  const words = q.split(/\s+/).filter(Boolean)

  return TOOLS.filter((tool) => {
    const fullText = `${tool.title} ${tool.shortTitle} ${tool.description} ${tool.categoryLabel} ${tool.tags.join(' ')} ${tool.searchKeywords.join(' ')}`.toLowerCase()
    
    // Direct full phrase match
    if (fullText.includes(q)) return true

    // All separate words match
    return words.every((word) => fullText.includes(word))
  })
}
